"""Generate design/INDEX.md from the frontmatter of every design/*/DECISION.md.

Flat: every decision appears once, in one list, and a reader picks from it and opens that record.
Active and superseded decisions are listed apart because they are read for different reasons: the
active list is what we do; the superseded list exists so an abandoned approach is not re-proposed.

The frontmatter is a flat YAML mapping of strings and lists of strings, so this reads it without a
YAML library: one `key: value` per line, a value either bare, double-quoted, or a `[a, b]` list.

usage: tools/build-design-index.py            (from the workspace root; rewrites design/INDEX.md)
       tools/build-design-index.py --check    (exit 1 if design/INDEX.md is not what it would write)
"""
import sys
from pathlib import Path

sys.dont_write_bytecode = True

REPO = Path(__file__).resolve().parent.parent
DESIGN = REPO / "design"
INDEX = DESIGN / "INDEX.md"

REQUIRED = ("title", "date", "status", "one_line", "revisit_if")
KNOWN = REQUIRED + ("tags", "confidence")


def parse_value(path, key, raw):
    raw = raw.strip()
    if raw.startswith("[") and raw.endswith("]"):
        return [item.strip().strip('"') for item in raw[1:-1].split(",") if item.strip()]
    if raw.startswith('"'):
        assert raw.endswith('"') and len(raw) >= 2, f"{path}: {key}: unterminated quote"
        return raw[1:-1].replace('\\"', '"')
    assert raw and raw[0] not in "'{" and ": " not in raw, f"{path}: {key}: quote this value"
    return raw


def read_frontmatter(path):
    text = path.read_text(encoding="utf-8")
    assert text.startswith("---\n"), f"{path}: no frontmatter"
    end = text.index("\n---\n", 4)
    meta = {}
    for line in text[4:end].splitlines():
        if not line.strip():
            continue
        assert ":" in line and not line[0].isspace(), f"{path}: frontmatter line is not key: value: {line!r}"
        key, raw = line.split(":", 1)
        key = key.strip()
        assert key in KNOWN, f"{path}: unknown frontmatter field {key}"
        assert key not in meta, f"{path}: {key} given twice"
        meta[key] = parse_value(path, key, raw)
    missing = [f for f in REQUIRED if not meta.get(f)]
    assert not missing, f"{path}: frontmatter missing {', '.join(missing)}"
    assert meta["status"] in ("active", "superseded"), f"{path}: status must be active or superseded"
    assert isinstance(meta.get("tags", []), list), f"{path}: tags must be a [list]"
    return meta


def render(docs):
    active = [d for d in docs if d["status"] == "active"]
    superseded = [d for d in docs if d["status"] == "superseded"]
    plural = "" if len(docs) == 1 else "s"
    out = [
        "<!-- GENERATED by tools/build-design-index.py. Do not hand-edit. -->",
        "",
        "# Design decisions",
        "",
        f"{len(docs)} record{plural}: {len(active)} active, {len(superseded)} superseded.",
        "",
        "Each record is what this project chose and why, on the information available at the time.",
        "It is not evidence. `README.md` says how a record is written and revised. Every record names",
        "in `revisit if` what would make it worth reopening.",
        "",
        "## Active",
        "",
    ]
    for d in sorted(active, key=lambda d: d["slug"]):
        out.append(f"- **[{d['slug']}](./{d['slug']}/DECISION.md)** ({d['date']}): {d['one_line']}")
        if d.get("confidence"):
            out.append(f"  - *confidence:* {d['confidence']}")
        out.append(f"  - *revisit if:* {d['revisit_if']}")
    if superseded:
        out += [
            "",
            "## Superseded",
            "",
            "Kept because the abandoned approach is one someone would otherwise propose again.",
            "",
        ]
        for d in sorted(superseded, key=lambda d: d["slug"]):
            out.append(f"- **[{d['slug']}](./{d['slug']}/DECISION.md)** ({d['date']}): {d['one_line']}")
    tags = {}
    for d in docs:
        for tag in d.get("tags", []):
            tags.setdefault(tag.lower(), set()).add(d["slug"])
    if tags:
        out += [
            "",
            "## By tag",
            "",
            "A view of the lists above. Nothing is reachable only through a tag.",
            "",
        ]
        for tag in sorted(tags):
            out.append(f"- `{tag}`: {', '.join(sorted(tags[tag]))}")
    out.append("")
    return "\n".join(out)


def main():
    docs = []
    for record in sorted(DESIGN.glob("*/DECISION.md")):
        meta = read_frontmatter(record)
        meta["slug"] = record.parent.name
        docs.append(meta)
    text = render(docs)
    if "--check" in sys.argv[1:]:
        current = INDEX.read_text(encoding="utf-8") if INDEX.exists() else ""
        if current != text:
            sys.exit(f"{INDEX.relative_to(REPO)} is stale: run tools/build-design-index.py")
        return
    INDEX.write_text(text, encoding="utf-8")
    print(f"{INDEX.relative_to(REPO)}: {len(docs)} record{'' if len(docs) == 1 else 's'}")


if __name__ == "__main__":
    main()
